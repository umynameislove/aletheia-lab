"""Phase 2 benchmark contract kernel.

This package holds the contract shared by every Phase 2 failure mechanism:
canonical serialization, family and candidate identity, the record schemas that
describe a candidate's journey from a prespecified slot to an accepted family,
and the validators that recompute census, cardinality and duplicate findings
from entry identifiers rather than from declared counts.

The kernel contains no mechanism-specific injection logic. Adding a mechanism
means adding a discriminated parameter model and its injector, not loosening
anything defined here.

Phase 1 identity, artifacts and hashes are untouched: Phase 2 uses its own
namespace so the two generations can never be mistaken for one another.
"""

