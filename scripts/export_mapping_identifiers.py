"""Generate browser validators from the packaged, frozen Unicode mapping policy."""
from __future__ import annotations

import argparse
from pathlib import Path

from aletheia_lab.project.mapping_identifiers import POLICY, codepoint_ranges


def character_class(value: str) -> str:
    return "".join(f"\\u{{{first:x}}}" + (f"-\\u{{{last:x}}}" if first != last else "")
                   for first, last in codepoint_ranges(value))


def build() -> str:
    return (f"// Generated by scripts/export_mapping_identifiers.py; Unicode {POLICY['unicode_version']}.\n"
            "// Source: packaged project/mapping_identifiers.json; runtime Unicode upgrades do not change this policy.\n"
            f"export const MAPPING_LETTERS_NUMBERS = /^[{character_class(POLICY['letters_numbers'])}]$/u;\n"
            f"export const MAPPING_MARKS = /^[{character_class(POLICY['marks'])}]$/u;\n"
            f"export const METRIC_LABEL_CHARACTERS = /^[{character_class(POLICY['labels'])}]+$/u;\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "dashboard/web/src/data/mapping-characters.ts"
    expected = build()
    if options.check:
        if destination.read_text(encoding="utf-8") != expected:
            raise SystemExit("Mapping character repertoire differs from the backend Unicode tables.")
    else:
        destination.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
